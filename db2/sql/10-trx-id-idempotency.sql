-- ===========================================================================
-- Redshark Bank - Db2 for z/OS UPGRADE
-- Add TRX_ID (12-digit PRIMARY KEY) + IDEMPOTENCY_KEY (UNIQUE) to an existing
-- BANKAPP.TRANSACTIONS table.
--
-- Target: Db2 9.1 for z/OS (DSN09015), subsystem DB9G, location DALLAS9
-- Run once, as IBMUSER, via SPUFI / DSNTEP2 / the JDBC bridge runner.
-- Fresh installs do NOT need this file - 09-transactions-notifications.sql
-- already creates the final table.
--
-- WHY THE TABLE IS REBUILT
-- Db2 9.1 for z/OS cannot ALTER COLUMN ... SET NOT NULL (SQLCODE -104), and a
-- PRIMARY KEY / UNIQUE constraint cannot be placed on a nullable column
-- (SQLCODE -542). The columns must therefore be created NOT NULL from the
-- start. The rebuild below preserves every historical row, including its ID
-- and CREATED_AT timestamp.
--
-- BACKFILL
--   TRX_ID          = 100000000000 + ID  ('1' || DIGITS(DECIMAL(ID,11,0))),
--                     always exactly 12 numeric digits and unique per row.
--   IDEMPOTENCY_KEY = REFERENCE, the original payment request identifier,
--                     so both sides of one transfer share the same key.
--
-- The new IDENTITY starts at 1000000 so freshly generated IDs cannot collide
-- with the explicitly copied legacy IDs on the UNIQUE (ID) constraint.
-- ===========================================================================

-- A leftover staging table from an interrupted run is safe to discard.
-- SQLCODE -204 here simply means there was none.
DROP TABLE BANKAPP.TRANSACTIONS_STAGE;

CREATE TABLE BANKAPP.TRANSACTIONS_STAGE
(
    ID               INTEGER       NOT NULL,
    TRX_ID           CHAR(12)      NOT NULL,
    USER_ID          INTEGER       NOT NULL,
    ACCOUNT_ID       INTEGER       NOT NULL,
    DIRECTION        VARCHAR(10)   NOT NULL,
    AMOUNT           DECIMAL(14,2) NOT NULL,
    COUNTERPARTY     VARCHAR(50)   NOT NULL,
    REFERENCE        CHAR(36)      NOT NULL,
    IDEMPOTENCY_KEY  CHAR(36)      NOT NULL,
    CREATED_AT       TIMESTAMP     NOT NULL
);

-- Stage the existing rows. The SELECT deliberately ignores any old TRX_ID /
-- IDEMPOTENCY_KEY columns, so this works both for the original 09 table and
-- for a partially upgraded one.
INSERT INTO BANKAPP.TRANSACTIONS_STAGE
       (ID, TRX_ID, USER_ID, ACCOUNT_ID, DIRECTION, AMOUNT,
        COUNTERPARTY, REFERENCE, IDEMPOTENCY_KEY, CREATED_AT)
SELECT ID,
       '1' || DIGITS(DECIMAL(ID, 11, 0)),
       USER_ID, ACCOUNT_ID, DIRECTION, AMOUNT,
       COUNTERPARTY, REFERENCE, REFERENCE, CREATED_AT
  FROM BANKAPP.TRANSACTIONS;

-- Sanity check before dropping anything: staged row count must equal the
-- original row count.
SELECT COUNT(*) AS STAGED_ROWS FROM BANKAPP.TRANSACTIONS_STAGE;

-- Drop the old table (and with it the old PK-on-ID / UX_TX_* indexes).
DROP TABLE BANKAPP.TRANSACTIONS;

CREATE TABLE BANKAPP.TRANSACTIONS
(
    ID               INTEGER       GENERATED BY DEFAULT AS IDENTITY
                                   (START WITH 1000000 INCREMENT BY 1),
    TRX_ID           CHAR(12)      NOT NULL,
    USER_ID          INTEGER       NOT NULL,
    ACCOUNT_ID       INTEGER       NOT NULL,
    DIRECTION        VARCHAR(10)   NOT NULL,
    AMOUNT           DECIMAL(14,2) NOT NULL,
    COUNTERPARTY     VARCHAR(50)   NOT NULL,
    REFERENCE        CHAR(36)      NOT NULL,
    IDEMPOTENCY_KEY  CHAR(36)      NOT NULL,
    CREATED_AT       TIMESTAMP     NOT NULL WITH DEFAULT,
    CONSTRAINT PK_TRANSACTIONS   PRIMARY KEY (TRX_ID),
    CONSTRAINT UQ_TX_ID          UNIQUE (ID),
    CONSTRAINT UQ_TX_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY, USER_ID)
);

CREATE INDEX BANKAPP.IX_TX_USER ON BANKAPP.TRANSACTIONS (USER_ID, CREATED_AT);

INSERT INTO BANKAPP.TRANSACTIONS
       (ID, TRX_ID, USER_ID, ACCOUNT_ID, DIRECTION, AMOUNT,
        COUNTERPARTY, REFERENCE, IDEMPOTENCY_KEY, CREATED_AT)
SELECT ID, TRX_ID, USER_ID, ACCOUNT_ID, DIRECTION, AMOUNT,
       COUNTERPARTY, REFERENCE, IDEMPOTENCY_KEY, CREATED_AT
  FROM BANKAPP.TRANSACTIONS_STAGE;

DROP TABLE BANKAPP.TRANSACTIONS_STAGE;

-- Live payments draw 12-digit TRX_IDs from this sequence. The 200000000000
-- range is disjoint from the 100000000000+ID backfill values.
-- If this sequence already exists (a previous partial run), drop it first.
CREATE SEQUENCE BANKAPP.TRX_ID_SEQ
    AS DECIMAL(12,0)
    START WITH 200000000000
    INCREMENT BY 1
    MINVALUE 200000000000
    MAXVALUE 999999999999
    NO CYCLE
    CACHE 20;

-- ---------------------------------------------------------------------------
-- Verify
-- ---------------------------------------------------------------------------
SELECT COUNT(*) AS TOTAL,
       MIN(TRX_ID) AS MIN_TRX_ID,
       MAX(TRX_ID) AS MAX_TRX_ID
  FROM BANKAPP.TRANSACTIONS;

SELECT TRX_ID, IDEMPOTENCY_KEY, DIRECTION, USER_ID
  FROM BANKAPP.TRANSACTIONS
 ORDER BY ID
 FETCH FIRST 10 ROWS ONLY;

SELECT CONSTNAME, TYPE FROM SYSIBM.SYSTABCONST
 WHERE TBCREATOR = 'BANKAPP' AND TBNAME = 'TRANSACTIONS';

SELECT NEXT VALUE FOR BANKAPP.TRX_ID_SEQ AS NEXT_TRX_ID
  FROM SYSIBM.SYSDUMMY1;
