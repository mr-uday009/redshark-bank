-- ===========================================================================
-- Redshark Bank - Db2 for z/OS DDL for transfers and notifications
-- Target: Db2 9.1 for z/OS (DSN09015), subsystem DB9G, location DALLAS9
-- Owner : IBMUSER   Schema: BANKAPP
--
-- Adds two tables to the existing BANKDB database. Run with SPUFI, DSNTEP2 or
-- any SQL client as IBMUSER, after 01-create-objects.sql.
--
-- As in 01-create-objects.sql, deliberately NO "IN BANKDB.BANKTS" clause: on
-- Db2 for z/OS an index must live in an index table space in the same database
-- as its table, so letting Db2 allocate the table space pairs automatically
-- avoids SQLCODE -540 / SQLSTATE 57001 on every INSERT.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- BANKAPP.TRANSACTIONS
--
-- One row per SIDE of a transfer: a SENT row for the payer and a RECEIVED row
-- for the payee, both carrying the same REFERENCE. Storing both sides means
-- the history query is a single indexed lookup on USER_ID - no self-join, and
-- no way for one side to go missing.
--
-- AMOUNT is always positive; DIRECTION carries the sign. That keeps SUM()
-- meaningful and avoids sign confusion in the UI.
-- ---------------------------------------------------------------------------
CREATE TABLE BANKAPP.TRANSACTIONS
(
    ID           INTEGER       GENERATED BY DEFAULT AS IDENTITY
                               (START WITH 1 INCREMENT BY 1),
    USER_ID      INTEGER       NOT NULL,
    ACCOUNT_ID   INTEGER       NOT NULL,
    DIRECTION    VARCHAR(10)   NOT NULL,
    AMOUNT       DECIMAL(14,2) NOT NULL,
    COUNTERPARTY VARCHAR(50)   NOT NULL,
    REFERENCE    CHAR(36)      NOT NULL,
    CREATED_AT   TIMESTAMP     NOT NULL WITH DEFAULT,
    CONSTRAINT PK_TRANSACTIONS PRIMARY KEY (ID)
);

CREATE INDEX BANKAPP.IX_TX_USER ON BANKAPP.TRANSACTIONS (USER_ID, CREATED_AT);

-- ---------------------------------------------------------------------------
-- BANKAPP.NOTIFICATIONS
--
-- READ is a reserved-ish word in some contexts; Db2 accepts it as a column
-- name but it must not be confused with the SQL keyword. If your tooling
-- objects, rename to IS_READ and update Db2Bridge.java to match.
-- ---------------------------------------------------------------------------
CREATE TABLE BANKAPP.NOTIFICATIONS
(
    ID         INTEGER      GENERATED BY DEFAULT AS IDENTITY
                            (START WITH 1 INCREMENT BY 1),
    USER_ID    INTEGER      NOT NULL,
    KIND       VARCHAR(24)  NOT NULL WITH DEFAULT 'info',
    MESSAGE    VARCHAR(255) NOT NULL,
    READ       SMALLINT     NOT NULL WITH DEFAULT 0,
    CREATED_AT TIMESTAMP    NOT NULL WITH DEFAULT,
    CONSTRAINT PK_NOTIFICATIONS PRIMARY KEY (ID)
);

CREATE INDEX BANKAPP.IX_NOTIF_USER ON BANKAPP.NOTIFICATIONS (USER_ID, READ);

-- ---------------------------------------------------------------------------
-- Verify
-- ---------------------------------------------------------------------------
SELECT NAME, CREATEDBY FROM SYSIBM.SYSTABLES
 WHERE CREATOR = 'BANKAPP' AND NAME IN ('TRANSACTIONS', 'NOTIFICATIONS');
