-- ---------------------------------------------------------------------------
-- 1. Database
--    NOTE: CREATE DATABASE leaves the database in STOPPED status. It must be
--    started before its tables can be used:
--        DSN SYSTEM(DB9G)
--        -START DATABASE(BANKDB)
--        END
--    (see jcl/START-DATABASE.jcl).  Without this step every access to the
--    tables fails with SQLCODE -540 / SQLSTATE 57001.
-- ---------------------------------------------------------------------------
CREATE DATABASE BANKDB;

-- ---------------------------------------------------------------------------
-- 2. Tables
--    IMPORTANT: do NOT add "IN BANKDB.BANKTS" here.
--    On Db2 for z/OS an index is placed in an index table space in the SAME
--    database as its table.  A single segmented table space cannot host both
--    tables and indexes, so if the tables live in a hand-made table space that
--    has no companion index table space, every INSERT/SELECT on a table that
--    has a PRIMARY KEY or unique index fails with SQLCODE -540 / SQLSTATE 57001.
--    Leaving the IN clause off lets Db2 allocate a matching table space and
--    index table space automatically, which works correctly.
-- ---------------------------------------------------------------------------
CREATE TABLE BANKAPP.USERS
(
    ID            INTEGER      GENERATED BY DEFAULT AS IDENTITY
                               (START WITH 1 INCREMENT BY 1),
    USERNAME      VARCHAR(50)  NOT NULL,
    EMAIL         VARCHAR(255) NOT NULL,
    FULL_NAME     VARCHAR(100) NOT NULL,
    PASSWORD_HASH CHAR(64)     NOT NULL,
    CREATED_AT    TIMESTAMP    NOT NULL WITH DEFAULT,
    CONSTRAINT PK_USERS PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX BANKAPP.IX_USERS_USERNAME ON BANKAPP.USERS (USERNAME);
CREATE UNIQUE INDEX BANKAPP.IX_USERS_EMAIL    ON BANKAPP.USERS (EMAIL);

CREATE TABLE BANKAPP.ACCOUNTS
(
    ID             INTEGER       GENERATED BY DEFAULT AS IDENTITY
                                 (START WITH 1 INCREMENT BY 1),
    USER_ID        INTEGER       NOT NULL,
    ACCOUNT_NUMBER CHAR(12)      NOT NULL,
    ACCOUNT_TYPE   VARCHAR(20)   NOT NULL WITH DEFAULT 'CHECKING',
    BALANCE        DECIMAL(14,2) NOT NULL WITH DEFAULT 0,
    CREATED_AT     TIMESTAMP     NOT NULL WITH DEFAULT,
    CONSTRAINT PK_ACCOUNTS PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX BANKAPP.IX_ACCOUNTS_NUMBER ON BANKAPP.ACCOUNTS (ACCOUNT_NUMBER);

